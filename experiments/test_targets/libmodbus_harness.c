/* ─── CRC-16/Modbus function (verbatim from libmodbus) ──────────────── */

static uint16_t crc16(uint8_t *buffer, uint16_t buffer_length)
{
    uint8_t crc_hi = 0xFF; /* high CRC byte initialized */
    uint8_t crc_lo = 0xFF; /* low CRC byte initialized */
    unsigned int i;        /* will index into CRC lookup */

    /* pass through message buffer */
    while (buffer_length--) {
        i = crc_lo ^ *buffer++; /* calculate the CRC  */
        crc_lo = crc_hi ^ table_crc_hi[i];
        crc_hi = table_crc_lo[i];
    }

    return (crc_hi << 8 | crc_lo);
}


/* ─── Modbus RTU integrity check (from _modbus_rtu_check_integrity) ── */

/*
 * Validates a Modbus RTU frame:
 *   msg[0]           = slave address (1-247)
 *   msg[1]           = function code (1-127)
 *   msg[2..N-3]      = data payload
 *   msg[N-2..N-1]    = CRC-16 (little-endian: low byte first)
 *
 * The CRC is computed over msg[0..N-3] and compared against msg[N-2..N-1].
 */
static int check_modbus_rtu_integrity(uint8_t *msg, int msg_length)
{
    uint16_t crc_calculated;
    uint16_t crc_received;

    /* Minimum meaningful RTU frame: slave(1) + func(1) + data(>=1) + CRC(2) = 5 bytes.
     * Real Modbus requests have at least 2 data bytes (address field), so require 6. */
    if (msg_length < 6) {
        fprintf(stderr, "REJECT: Frame too short (%d bytes, need >= 6)\n", msg_length);
        return -1;
    }

    /* Pre-validate slave address and function code BEFORE CRC.
     * This prevents degenerate CRC matches (e.g., 0xFFFF → CRC=0x0000)
     * from counting as bypasses. */
    uint8_t slave = msg[0];
    uint8_t function_code = msg[1];

    if (slave == 0 || slave > 247) {
        fprintf(stderr, "REJECT: Invalid slave address 0x%02X (need 1-247)\n", slave);
        return -1;
    }

    if (function_code < 1 || function_code > 127) {
        fprintf(stderr, "REJECT: Invalid function code 0x%02X (need 1-127)\n", function_code);
        return -1;
    }

    /* Compute CRC over everything except the last 2 bytes */
    crc_calculated = crc16(msg, msg_length - 2);

    /* Extract received CRC (little-endian: low byte at msg[N-2]) */
    crc_received = (msg[msg_length - 1] << 8) | msg[msg_length - 2];

    if (crc_calculated != crc_received) {
        fprintf(stderr, "REJECT: CRC mismatch (calculated=0x%04X received=0x%04X)\n",
                crc_calculated, crc_received);
        return -1;
    }

    /* Full validation passed: valid slave + valid function + correct CRC */
    printf("MODBUS_CRC_PASS: CRC-16 validated (0x%04X)\n", crc_calculated);
    printf("MODBUS_FRAME_VALID: func=%d slave=%d datalen=%d\n",
           function_code, slave, msg_length - 4);
    printf("  [!] Bypassed CRC-16/Modbus math wall!\n");

    /* Print data bytes for verification */
    printf("  DATA: ");
    int data_len = msg_length - 4;  /* exclude slave + func + CRC */
    int print_len = data_len < 32 ? data_len : 32;
    for (int i = 0; i < print_len; i++) {
        printf("%02X ", msg[2 + i]);
    }
    printf("\n");

    return msg_length;
}


/* ─── Main ───────────────────────────────────────────────────────────── */

int main(int argc, char *argv[])
{
    uint8_t buf[1024];
    size_t len = 0;

    if (argc > 1) {
        /* File argument mode (for AFL++ @@ and GDB probing) */
        FILE *fp = fopen(argv[1], "rb");
        if (!fp) {
            perror("fopen");
            return 1;
        }
        len = fread(buf, 1, sizeof(buf), fp);
        fclose(fp);
    } else {
        /* Stdin mode (fallback) */
        len = fread(buf, 1, sizeof(buf), stdin);
    }

    if (len == 0) {
        fprintf(stderr, "REJECT: Empty input\n");
        return 1;
    }

    int result = check_modbus_rtu_integrity(buf, (int)len);

    return (result > 0) ? 0 : 1;
}
