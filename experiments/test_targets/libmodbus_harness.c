/*
 * libmodbus_harness.c — AFL++ harness for libmodbus CRC-16/Modbus validation
 *
 * Feeds raw AFL input as a Modbus RTU frame and validates the CRC-16.
 * Uses the REAL libmodbus CRC lookup tables and crc16() function
 * (included directly from modbus-rtu.c).
 *
 * The CRC-16/Modbus algorithm:
 *   - Polynomial: 0xA001 (reflected 0x8005)
 *   - Init:       0xFFFF
 *   - Table-driven with 256-entry hi/lo tables
 *   - CRC is appended little-endian (low byte first)
 *
 * This is a genuine math wall: probability of random CRC match is
 * 1/65536 per frame. AFL++ cannot brute-force this.
 *
 * Bypass markers (for test_generalization_matrix.py):
 *   "MODBUS_CRC_PASS"    — CRC-16 validated successfully
 *   "MODBUS_FRAME_VALID" — CRC valid + valid function code
 *
 * Build: see build_libmodbus_harness.sh
 *
 * Input mode:
 *   - argv[1]: file path (for AFL++ @@ mode and GDB probing)
 *   - stdin:   fallback if no argv[1]
 */

